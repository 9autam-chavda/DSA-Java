package bitManipulation;

public class P1bitWiseOperator {
    public static void main(String[] args) {
        System.out.println(4&5);
        System.out.println(4|5);
        System.out.println(4^5);
        System.out.println(~9);
        System.out.println(9<<3);
        System.out.println(9>>1);
    }
    
}
